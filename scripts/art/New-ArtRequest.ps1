#Requires -Version 5.1
<#
  New-ArtRequest.ps1 (cc-P152): file an art request for something Chase must make, instead of only writing a brief in
  notes. It lands in D:\UO\art\requests\<id>.json with status "new"; the console's Art tab (and later the web console)
  shows it, and Chase generates, imports, approves and places it from there. Nothing is generated by filing.

    powershell -NoProfile -ExecutionPolicy Bypass -File D:\ShatteredLegacy\scripts\art\New-ArtRequest.ps1 `
        -Id achievements-button -Title 'The Achievements paperdoll button' -AskedBy P147 `
        -Subject 'A 64 x 21 paperdoll button reading "Deeds" in a condensed blackletter ...' `
        -Slots @(@{ file = '22456.png'; sizes = @(, @(64, 21)); transparent = $true; budgetKB = 20; margin = 0 }) `
        -Destination @{ kind = 'game-gump'; folder = 'player-package\vendor\shattered-legacy-art\gumps' } `
        -Note 'Brief: notes\art\achievements-button\BRIEF.md'

  A slot: file, sizes (a list of [w, h], or of n for n x n; the first is placed under the file name), kind (static,
  animated, tile, band), frames and fps (animated), animation (pulse-turn, halo-sparks, spinner), transparent, budgetKB,
  margin (clear pixels kept round a transparent object), glow [r, g, b], toneLow / toneHigh [r, g, b] (tiles).
  Destination kind: console, game-gump, game-item, game-anim or web, with folder relative to D:\ShatteredLegacy (or
  absolute). Game art also needs its IDs registered through the P26 pipeline (scripts\find-free-art.py and
  player-package\vendor\shattered-legacy-art\registry.csv) before it is placed.
  Prints the filed request as JSON; exit 1 (and nothing filed) when it is malformed or the id is taken.
#>
param(
    [Parameter(Mandatory)][string]$Id,
    [Parameter(Mandatory)][string]$Title,
    [Parameter(Mandatory)][string]$AskedBy,
    [Parameter(Mandatory)][string]$Subject,
    [Parameter(Mandatory)][object[]]$Slots,
    [Parameter(Mandatory)][hashtable]$Destination,
    [string]$Style = '',
    [string]$Note = '',
    [string]$StoreRoot = 'D:\UO\art'
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'ArtLib.ps1')
$cfg = Get-ArtConfig -StoreRoot $StoreRoot
try {
    $s = @(foreach ($x in $Slots) {
        $h = $(if ($x -is [hashtable]) { $x } else { $t = @{}; foreach ($p in $x.PSObject.Properties) { $t[$p.Name] = $p.Value }; $t })
        $a = @{ File = [string]$h.file; Sizes = @($h.sizes) }
        foreach ($k in @('kind', 'frames', 'fps', 'animation', 'transparent', 'budgetKB', 'margin', 'glow', 'toneLow', 'toneHigh')) { if ($h.ContainsKey($k)) { $a[$k] = $h[$k] } }
        New-ArtSlot @a
    })
    $r = New-ArtRequestObject -Id $Id -Title $Title -AskedBy $AskedBy -Style $Style -Subject $Subject -Slots $s -Destination ([pscustomobject]$Destination) -Note $Note
    if (Test-Path -LiteralPath (Get-ArtRequestPath $cfg $Id)) { throw ('a request ' + $Id + ' already exists in ' + $cfg.Requests) }
    Save-ArtRequest $cfg $r
    Add-ArtLine $cfg.Log ([ordered]@{ at = (Get-ArtNow); action = 'new'; id = $Id; by = $AskedBy })
    [pscustomobject]@{ ok = $true; why = ('filed ' + $Id + ' in ' + $cfg.Requests); request = $r } | ConvertTo-Json -Depth 8
} catch {
    [pscustomobject]@{ ok = $false; why = $_.Exception.Message } | ConvertTo-Json
    exit 1
}
